-- 3. OFERTA ACADÉMICA Y PERIODOS
CREATE TABLE periodos (
    periodo_id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    clave_periodo VARCHAR(10) NOT NULL UNIQUE,
    nombre VARCHAR(50) NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    limite_captura_calificaciones DATE NOT NULL,
    captura_activa CHAR(1) DEFAULT 'N' NOT NULL CHECK (captura_activa IN ('S', 'N')),
    CONSTRAINT chk_periodo_fechas CHECK (
        fecha_inicio < fecha_fin
        AND limite_captura_calificaciones >= fecha_inicio
    )
);

CREATE TABLE materias (
    creditos NUMBER(2) NOT NULL CHECK (creditos > 0),
    id_carrera NUMBER NOT NULL REFERENCES carreras(id_carrera),
    materia_id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    clave_materia VARCHAR(20) NOT NULL,
    nombre_materia VARCHAR(100) NOT NULL,
    creditos DECIMAL(2,0) NOT NULL CHECK (creditos > 0),
    id_carrera BIGINT NOT NULL,
    CONSTRAINT uk_materia_carrera_clave UNIQUE (id_carrera, clave_materia),
    CONSTRAINT uk_materia_id_carrera UNIQUE (materia_id, id_carrera),
    CONSTRAINT fk_materias_id_carrera FOREIGN KEY (id_carrera) REFERENCES carreras(id_carrera)
);

CREATE TABLE prerrequisitos_materia (
    materia_id BIGINT NOT NULL,
