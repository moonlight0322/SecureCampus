-- 1. CATÁLOGOS GENERALES E INFRAESTRUCTURA
-- Los IDs reservados para nuevos roles y carreras comienzan después de las semillas.
CREATE TABLE roles (
    rol_id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    nombre_rol VARCHAR(30) NOT NULL UNIQUE
) AUTO_INCREMENT = 4;

CREATE TABLE carreras (
    id_carrera BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    clave_carrera VARCHAR(20) NOT NULL UNIQUE,
    nombre_carrera VARCHAR(100) NOT NULL
) AUTO_INCREMENT = 19;

CREATE TABLE edificios (
    id_edificio BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    clave_edificio VARCHAR(10) NOT NULL UNIQUE,
    nombre_edificio VARCHAR(50) NOT NULL
);

CREATE TABLE aulas (
    id_aula BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    id_edificio BIGINT NOT NULL,
    nombre_aula VARCHAR(30) NOT NULL,
    capacidad DECIMAL(3,0) DEFAULT 30 NOT NULL CHECK (capacidad > 0),
    tipo_aula VARCHAR(30) DEFAULT 'TEORICA' NOT NULL
        CHECK (tipo_aula IN ('TEORICA', 'LABORATORIO', 'TALLER', 'AUDITORIO')),
    CONSTRAINT fk_aulas_id_edificio FOREIGN KEY (id_edificio) REFERENCES edificios(id_edificio)
);

-- 2. PERFILES BASE
CREATE TABLE perfiles_base (
    rol_id NUMBER NOT NULL REFERENCES roles(rol_id),
    nombre VARCHAR2(50) NOT NULL,
    apellido_paterno VARCHAR2(50) NOT NULL,
    apellido_materno VARCHAR2(50),
    fecha_nacimiento DATE,
    domicilio VARCHAR2(200),
    telefono VARCHAR2(15),
    correo_institucional VARCHAR2(100) NOT NULL UNIQUE,
    activo NUMBER(1) DEFAULT 1 NOT NULL CHECK (activo IN (0, 1)),
